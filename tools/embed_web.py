"""PlatformIO pre-build step: compresses the files in web/ into src/web_files.h, so the
clock can serve its settings page from flash. Runs on every build (see platformio.ini) and
only rewrites the header when something changed. Can also be run by hand: python tools/embed_web.py"""
import gzip
from pathlib import Path

TYPES = {".html": "text/html; charset=utf-8", ".png": "image/png", ".js": "text/javascript",
         ".css": "text/css", ".svg": "image/svg+xml", ".json": "application/json"}


def generate(root: Path) -> None:
    web, out = root / "web", root / "src" / "web_files.h"
    lines = ["// Generated by tools/embed_web.py from the files in web/. Don't edit; edit web/ instead.",
             "#pragma once", "#include <stddef.h>", "#include <stdint.h>", "",
             "struct WebFile {", "  const char *path;  // URL", "  const char *type;",
             "  const uint8_t *data;  // gzip", "  size_t len;", "};", ""]
    entries = []
    for f in sorted(p for p in web.iterdir() if p.suffix in TYPES):
        data = gzip.compress(f.read_bytes(), 9, mtime=0)  # mtime 0: same input, same output
        name = "kWeb_" + "".join(ch if ch.isalnum() else "_" for ch in f.name)
        body = ",".join(str(b) for b in data)
        lines.append(f"static const uint8_t {name}[] = {{{body}}};  // {f.name}, {len(data)} bytes gzipped")
        url = "/" if f.name == "index.html" else "/" + f.name
        entries.append(f'    {{"{url}", "{TYPES[f.suffix]}", {name}, sizeof({name})}},')
    lines += ["", "static const WebFile kWebFiles[] = {", *entries, "};", ""]
    text = "\n".join(lines)
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
        print(f"[embed_web] wrote {out.name} ({len(entries)} files)")


try:
    Import("env")  # noqa: F821  (defined by PlatformIO)
    generate(Path(env["PROJECT_DIR"]))  # noqa: F821
except NameError:
    generate(Path(__file__).resolve().parent.parent)
